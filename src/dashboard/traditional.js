export function toTraditional(value) {
  if (typeof value !== "string" || !value) return value;
  let result = value;
  phrasePairs.forEach(([simplified, traditional]) => { result = result.replaceAll(simplified, traditional); });
  return [...result].map((character) => characterPairs[character] || character).join("");
}
